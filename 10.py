# Задание 10.
# Даны два положительных целых числа.
# Найти их наибольший общий делитель алгоритмом Евклида.

a = int(input("Введите положительное A: "))
b = int(input("Введите положительное B: "))

if a <= 0 or b <= 0:
    print("Ошибка! Числа должны быть положительными.")
else:
    x = a
    y = b

    while y != 0:
        remainder = x % y
        x = y
        y = remainder

    print("НОД =", x)