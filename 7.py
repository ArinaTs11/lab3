# Задание 7.
# Найти количество целых отрезков длины B,
# которые помещаются в отрезке длины A,
# и длину незанятой части.
# Умножение и деление не использовать.

a = float(input("Введите длину A: "))
b = float(input("Введите длину B: "))

if a <= 0 or b <= 0 or a < b:
    print("Ошибка! A и B должны быть положительными, A >= B.")
else:
    remainder = a
    count = 0

    while remainder >= b:
        remainder -= b
        count += 1

    print("Количество целых отрезков =", count)
    print("Длина незанятой части =", round(remainder, 10))