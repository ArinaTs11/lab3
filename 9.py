# Задание 9.
# Первоначальный вклад — 1000 рублей.
# Каждый месяц вклад увеличивается на P процентов.
# Найти количество месяцев, за которое вклад превысит 1100 рублей.

p = float(input("Введите процент P (от 0 до 25): "))

if p <= 0 or p >= 25:
    print("Ошибка! P должно быть больше 0 и меньше 25.")
else:
    deposit = 1000.0
    months = 0

    while deposit <= 1100:
        deposit += deposit * p / 100
        months += 1

    print("Количество месяцев =", months)
    print("Итоговый вклад =", round(deposit, 2), "руб.")